// Helper function to find a blog post by slug, numeric ID, or title
window.getBlogPostById = function(identifier) {
  if (!identifier) return window.BLOG_POSTS_DATA[0];
  const str = String(identifier).toLowerCase().trim();
  
  // 1. Exact match on slug or id
  let found = window.BLOG_POSTS_DATA.find(p => p.slug.toLowerCase() === str || p.id.toLowerCase() === str);
  if (found) return found;

  // 2. Match on numeric index (1-based)
  const num = parseInt(str, 10);
  if (!isNaN(num) && num >= 1 && num <= window.BLOG_POSTS_DATA.length) {
    return window.BLOG_POSTS_DATA[num - 1];
  }

  // 3. Match on image filename
  found = window.BLOG_POSTS_DATA.find(p => p.imgSrc.toLowerCase().includes(str));
  if (found) return found;

  // 4. Fuzzy match on title
  found = window.BLOG_POSTS_DATA.find(p => p.title.toLowerCase().includes(str) || str.includes(p.title.toLowerCase()));
  if (found) return found;

  // Default fallback
  return window.BLOG_POSTS_DATA[0];
};
